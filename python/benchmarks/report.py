"""Run the suite N times, interleaved, and write docs/BENCHMARKS.md.

    PYTHONPATH=build/python/python uv run --group bench python python/benchmarks/report.py --runs 3 --label "$(git describe --always)"

Min of per-run medians is reported (the machine drifts thermally); ``spread`` is
(max - min) / min across runs, so a row whose spread exceeds the gap between two
backends decides nothing.
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import platform
import re
import subprocess
import sys
import tempfile
from importlib import metadata
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
PACKAGES = ("seitz", "spglib", "moyopy", "pymatgen", "ase", "pyxtal", "gemmi")


def run_suite(runs: int, out: Path, pytest_args: list[str]) -> list[Path]:
    files = [out / f"run{i}.json" for i in range(runs)]
    for f in files:
        subprocess.run([sys.executable, "-m", "pytest", str(ROOT / "python/benchmarks"), "--benchmark-only",
                        "-q", f"--benchmark-json={f}", *pytest_args], check=True, cwd=ROOT)
    return files


def load(files: list[Path]) -> pd.DataFrame:
    frames = [pd.json_normalize(json.loads(f.read_text())["benchmarks"]).assign(run=i) for i, f in enumerate(files)]
    df = pd.concat(frames)[["run", "group", "extra_info.backend", "stats.median"]]
    return df.set_axis(["run", "group", "backend", "median"], axis=1)


def table(df: pd.DataFrame) -> pd.DataFrame:
    by = df.groupby(["group", "backend"])["median"]
    best, spread = by.min(), ((by.max() - by.min()) / by.min())
    wide = best.unstack("backend").reindex(columns=[p for p in PACKAGES if p in best.index.levels[1]])
    wide["spread"] = spread.groupby("group").max()
    if {"seitz", "spglib"} <= set(wide):
        wide.insert(1, "seitz / spglib", wide["seitz"] / wide["spglib"])
    atoms = wide.index.str.extract(r"-(\d+)$")[0].fillna("0").astype(int)
    return wide.iloc[sorted(range(len(wide)), key=lambda i: (wide.index[i].split(":")[0], atoms[i]))]


def version(pkg: str) -> str:
    try: return metadata.version(pkg)
    except metadata.PackageNotFoundError: return "-"


def cpu() -> str:
    m = re.search(r"model name\s*:\s*(.+)", Path("/proc/cpuinfo").read_text()) if Path("/proc/cpuinfo").exists() else None
    return m.group(1).strip() if m else platform.processor() or platform.machine()


def render(t: pd.DataFrame, runs: int, label: str, files: int | None) -> str:
    versions = ", ".join(f"{p} {version(p)}" for p in PACKAGES if p in t.columns)
    return f"""# Benchmarks

Seconds per call, min of per-run medians over {runs} interleaved passes of the whole
suite; `spread` is the worst (max-min)/min across passes for that row. Timed: the
engine call only, with each package's native object built beforehand and a fresh
Seitz analyzer per call (its memo is never warm). `symprec = 1e-5`, angle
tolerance derived, everywhere. Generated by `python/benchmarks/report.py`.

- {dt.date.today()}, Seitz {label}, {cpu()}, Python {platform.python_version()}
- {versions}
- `read_cif`: PyXtal's shipped real-structure corpus{f', the {files} files every backend parses' if files else ''}
- moyopy computes dataset, standardized and primitive cells in one call, so its
  three rows time the same work; PyXtal's `from_seed` also assigns Wyckoff
  positions; gemmi parses and expands only, with no symmetry search.

{t.to_markdown(floatfmt=".3g", missingval="-")}
"""


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--runs", type=int, default=3)
    ap.add_argument("--label", default="(unlabelled)", help="git describe, pasted in")
    ap.add_argument("--json", nargs="*", type=Path, help="aggregate these instead of running")
    ap.add_argument("--out", type=Path, default=ROOT / "docs/BENCHMARKS.md")
    ap.add_argument("pytest_args", nargs="*", help="after --, e.g. -k rocksalt-128")
    a = ap.parse_args()
    files = a.json or run_suite(a.runs, Path(tempfile.mkdtemp(prefix="seitz-bench-")), a.pytest_args)
    raw = json.loads(files[0].read_text())["benchmarks"]
    n_cif = next((b["extra_info"].get("files") for b in raw if b["group"] == "read_cif"), None)
    text = render(table(load(files)), len(files), a.label, n_cif)
    a.out.write_text(text)
    print(text)


if __name__ == "__main__":
    main()
